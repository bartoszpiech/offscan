/// Parent suite for every test that touches the HEIC fixtures. `.serialized` is inherited by the
/// nested suites, so at most one full-size photo is processed at a time (bounded memory).
@Suite(.serialized) enum FixtureTests {}

// MARK: - Photo fixtures

enum Fixtures {
    struct Expected: Decodable {
        /// Floor for every single fixture.
        var minimumMatchRatio: Double
        /// Floor for the mean over all fixtures (the stricter, more stable check).
        var minimumAverageMatchRatio: Double
        var fixtures: [String: Fixture]
    }

    struct Fixture: Decodable {
        var orientation: String
        var title: String
        var words: [String]
        var isLandscape: Bool { orientation == "landscape" }
    }

    /// The directory that contains `TestFixtures/`, found by walking up from this source file.
    static let repoRoot: URL = {
        var url = URL(fileURLWithPath: #filePath).deletingLastPathComponent()
        while url.path != "/" {
            if FileManager.default.fileExists(atPath: url.appendingPathComponent("TestFixtures/expected.json").path) {
                return url
            }
            url = url.deletingLastPathComponent()
        }
        fatalError("TestFixtures not found above \(#filePath)")
    }()

    /// The fixture sets: the synthetic photos in `TestFixtures` (generated by
    /// scripts/generate-fixtures.sh, checked in) and, when present, real photos in
    /// `TestFixtures/private` (same layout, git-ignored, never published).
    private static let sets: [URL] = {
        let root = repoRoot.appendingPathComponent("TestFixtures")
        let personal = root.appendingPathComponent("private")
        let hasPersonal = FileManager.default.fileExists(atPath: personal.appendingPathComponent("expected.json").path)
        return hasPersonal ? [root, personal] : [root]
    }()

    private static func load(_ directory: URL) -> Expected {
        let url = directory.appendingPathComponent("expected.json")
        do {
            return try JSONDecoder().decode(Expected.self, from: Data(contentsOf: url))
        } catch {
            fatalError("Cannot load \(url.path): \(error)")
        }
    }

    /// Thresholds from the checked-in set; fixtures from every set.
    static let expected: Expected = {
        var merged = load(sets[0])
        for directory in sets.dropFirst() {
            merged.fixtures.merge(load(directory).fixtures) { first, _ in first }
        }
        return merged
    }()

    /// Where each fixture's photo is.
    private static let photoDirectories: [String: URL] = {
        var directories: [String: URL] = [:]
        for directory in sets.reversed() {
            for name in load(directory).fixtures.keys { directories[name] = directory.appendingPathComponent("photos") }
        }
        return directories
    }()

    /// Fixture file names, sorted (stable test argument order).
    static let names: [String] = expected.fixtures.keys.sorted()

    /// A few fixtures for the slower tests: the first portrait and landscape of the checked-in set.
    static let sampleNames: [String] = {
        let checkedIn = load(sets[0]).fixtures
        let portrait = checkedIn.keys.sorted().first { !checkedIn[$0]!.isLandscape }
        let landscape = checkedIn.keys.sorted().first { checkedIn[$0]!.isLandscape }
        return [portrait, landscape].compactMap { $0 }
    }()

    static func fixture(_ name: String) -> Fixture { expected.fixtures[name]! }

    static func url(_ name: String) -> URL { photoDirectories[name]!.appendingPathComponent(name) }

    /// Decodes a fixture photo the way the import pipeline does (EXIF applied, ≤ `maxDimension`).
    static func photo(_ name: String, maxDimension: Int? = 3500) throws -> CGImage {
        try ImageCodec().decode(contentsOf: url(name), maxDimension: maxDimension)
    }
}

// MARK: - Pixel access

/// An sRGB 8-bit RGBA copy of a `CGImage`, addressed with a **top-left** origin.
struct Bitmap {
    struct Pixel: Equatable {
        var r: UInt8, g: UInt8, b: UInt8, a: UInt8
        var luminance: Double { 0.299 * Double(r) + 0.587 * Double(g) + 0.114 * Double(b) }
        var isRed: Bool { r > 180 && g < 80 && b < 80 }
    }

    let width: Int
    let height: Int
    let bytes: [UInt8]

    init(_ image: CGImage) {
        let width = image.width, height = image.height
        self.width = width
        self.height = height
        var data = [UInt8](repeating: 0, count: width * height * 4)
        data.withUnsafeMutableBytes { buffer in
            let ctx = CGContext(
                data: buffer.baseAddress, width: width, height: height, bitsPerComponent: 8,
                bytesPerRow: width * 4, space: CGColorSpace(name: CGColorSpace.sRGB)!,
                bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue
            )!
            ctx.draw(image, in: CGRect(x: 0, y: 0, width: width, height: height))
        }
        bytes = data
    }

    /// `x`, `y` in pixels, top-left origin (bitmap memory is stored top row first).
    subscript(x: Int, y: Int) -> Pixel {
        let i = (y * width + x) * 4
        return Pixel(r: bytes[i], g: bytes[i + 1], b: bytes[i + 2], a: bytes[i + 3])
    }

    /// Fraction of all pixels for which `predicate` holds.
    func fraction(where predicate: (Pixel) -> Bool) -> Double {
        var count = 0
        for y in 0..<height { for x in 0..<width where predicate(self[x, y]) { count += 1 } }
        return Double(count) / Double(width * height)
    }
}

// MARK: - Synthetic images

enum Synthetic {
    /// Creates an sRGB RGBA image; `draw` receives a context with a **bottom-left** origin.
    static func image(width: Int, height: Int, background: CGColor? = nil, _ draw: (CGContext) -> Void = { _ in }) -> CGImage {
        let ctx = CGContext(
            data: nil, width: width, height: height, bitsPerComponent: 8, bytesPerRow: 0,
            space: CGColorSpace(name: CGColorSpace.sRGB)!,
            bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue
        )!
        if let background {
            ctx.setFillColor(background)
            ctx.fill(CGRect(x: 0, y: 0, width: width, height: height))
        }
        draw(ctx)
        return ctx.makeImage()!
    }

    static func gray(_ v: CGFloat) -> CGColor { CGColor(srgbRed: v, green: v, blue: v, alpha: 1) }
    static let red = CGColor(srgbRed: 1, green: 0, blue: 0, alpha: 1)

    /// Converts a top-left-origin rect to the bottom-left-origin space of a context of `height`.
    static func flip(_ rect: CGRect, height: Int) -> CGRect {
        CGRect(x: rect.minX, y: CGFloat(height) - rect.maxY, width: rect.width, height: rect.height)
    }

    /// Draws `text` with its baseline origin at `point` (bottom-left origin). Returns the glyph
    /// bounds in the context's (bottom-left) coordinates.
    @discardableResult
    static func drawText(_ text: String, at point: CGPoint, size: CGFloat, in ctx: CGContext, color: CGColor = gray(0)) -> CGRect {
        let font = CTFontCreateWithName("Helvetica" as CFString, size, nil)
        let attributes: [NSAttributedString.Key: Any] = [
            NSAttributedString.Key(kCTFontAttributeName as String): font,
            NSAttributedString.Key(kCTForegroundColorAttributeName as String): color,
        ]
        let line = CTLineCreateWithAttributedString(NSAttributedString(string: text, attributes: attributes))
        ctx.textPosition = point
        let bounds = CTLineGetImageBounds(line, ctx)
        CTLineDraw(line, ctx)
        return bounds
    }

    /// Small image with a red square in its top-left corner (`square` px) on a white background.
    static func redCornerImage(width: Int, height: Int, square: Int = 40) -> CGImage {
        image(width: width, height: height, background: gray(1)) { ctx in
            ctx.setFillColor(red)
            ctx.fill(flip(CGRect(x: 0, y: 0, width: square, height: square), height: height))
        }
    }
}
